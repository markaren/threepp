// Vulkan deferred — the 5 inch race quad (python/examples/uav/racer.glb) flies through a solved smoke plume.
//
// The smoke is a ParticleField::GridSmoke (see vulkan_smoke.cpp for the solver). What this adds is a body that
// moves FAST through it and has to read right:
//
//   * the quad is a swept capsule for the centre stack and four swept spheres for the motors — "swept" because a
//     quad at 5 m/s covers three cells a solver step and a capsule at only its current position would let the
//     smoke slip through; each collider runs from where the part was one step ago to where it is now, with the
//     velocity of that move, so the air is carried along and left in a wake;
//   * every rotor is a SOURCE with no smoke and a downward velocity along the quad's thrust axis, which is the
//     downwash: it carves the plume, and as the quad banks the wash is thrown sideways, which is where the
//     smoke goes. The speed goes as the square root of the thrust, as a rotor's induced velocity does.
//
// The flight is a closed form in t (a figure-eight through the plume), and the attitude is what the path asks
// of a quad: the thrust vector is a + g, the body's up axis lies along it, the nose along the ground track, so
// the quad leans into every turn. The numbers are racer_spec.json's: the rotors' places, the 0.45 drawn scale,
// the spin senses. The Python flight rig is not used here (no threepp.dll swap, no Python), so this is a
// kinematic stand-in: replaying a flown lap's telemetry would be the faithful next step.
//
// Controls:  drag = orbit   scroll = zoom
// Headless:  vulkan_smoke_drone --shot out.png [--t SECONDS] [--res N] [--cam x,y,z --look x,y,z] [--track]
//            vulkan_smoke_drone --film DIR [--seconds S] [--fps F] [--track]
//            --drone PATH   another racer.glb (it is generated by python/examples/uav/build_racer_blender.py)
//            --no-drone     the plume alone (the A leg of the reaction test)

#include "capture_util.hpp"
#include "smoke_quad.hpp"

#include "threepp/geometries/CircleGeometry.hpp"
#include "threepp/geometries/PlaneGeometry.hpp"
#include "threepp/lights/DirectionalLight.hpp"
#include "threepp/loaders/GLTFLoader.hpp"
#include "threepp/loaders/RGBELoader.hpp"
#include "threepp/materials/MeshBasicMaterial.hpp"
#include "threepp/materials/MeshStandardMaterial.hpp"
#include "threepp/textures/DataTexture.hpp"
#include "threepp/objects/ParticleField.hpp"
#include "threepp/renderers/VulkanRenderer.hpp"
#include "threepp/threepp.hpp"

#include <algorithm>
#include <cmath>
#include <cstdio>
#include <cstdlib>
#include <filesystem>
#include <iostream>
#include <vector>
#include <memory>
#include <string>

using namespace threepp;

using namespace smokedemo;

int main(int argc, char** argv) {

    std::string shotPath, filmDir;
    std::filesystem::path dronePath = std::filesystem::path(__FILE__).parent_path() / ".." / ".." / "python" / "examples" / "uav" / "racer.glb";
    float seconds = 10.f, shotT = 6.f;
    int   fps = 60, res = 128;
    bool  noDrone = false, track = false, bench = false;
    int   iters = 28;
    std::string upscaler = "dlss";
    std::string sky;          // an HDRI from the data folder (textures/env/NAME.hdr): the sun comes from it
    float exposure = 1.0f, camDist = 2.4f, camAz = 25.f, camH = 1.25f, sunElev = 6.f, sunEnergy = 5.f, aniso = 0.35f;
    bool  backlit = false;
    float sigma = 6.f, vort = 6.f, buoy = 3.5f, rate = 8.f;
    for (int i = 1; i < argc; ++i) {
        const std::string a = argv[i];
        if (a == "--shot" && i + 1 < argc) shotPath = argv[++i];
        else if (a == "--film" && i + 1 < argc) filmDir = argv[++i];
        else if (a == "--drone" && i + 1 < argc) dronePath = argv[++i];
        else if (a == "--t" && i + 1 < argc) shotT = float(std::atof(argv[++i]));
        else if (a == "--seconds" && i + 1 < argc) seconds = float(std::atof(argv[++i]));
        else if (a == "--fps" && i + 1 < argc) fps = std::atoi(argv[++i]);
        else if (a == "--res" && i + 1 < argc) res = std::atoi(argv[++i]);
        else if (a == "--no-drone") noDrone = true;
        else if (a == "--track") track = true;
        else if (a == "--bench") bench = true;
        else if (a == "--iters" && i + 1 < argc) iters = std::atoi(argv[++i]);
        else if (a == "--upscaler" && i + 1 < argc) upscaler = argv[++i];
        else if (a == "--sky" && i + 1 < argc) sky = argv[++i];
        else if (a == "--exposure" && i + 1 < argc) exposure = float(std::atof(argv[++i]));
        else if (a == "--backlit") backlit = true;
        else if (a == "--aniso" && i + 1 < argc) aniso = float(std::atof(argv[++i]));
        else if (a == "--sun-elev" && i + 1 < argc) sunElev = float(std::atof(argv[++i]));
        else if (a == "--sun-energy" && i + 1 < argc) sunEnergy = float(std::atof(argv[++i]));
        else if (a == "--dist" && i + 1 < argc) camDist = float(std::atof(argv[++i]));
        else if (a == "--az" && i + 1 < argc) camAz = float(std::atof(argv[++i]));
        else if (a == "--camh" && i + 1 < argc) camH = float(std::atof(argv[++i]));
        else if (a == "--sigma" && i + 1 < argc) sigma = float(std::atof(argv[++i]));
        else if (a == "--vort" && i + 1 < argc) vort = float(std::atof(argv[++i]));
        else if (a == "--buoy" && i + 1 < argc) buoy = float(std::atof(argv[++i]));
        else if (a == "--rate" && i + 1 < argc) rate = float(std::atof(argv[++i]));
    }
    const capture::Args cap      = capture::parseArgs(argc, argv);
    const bool          headless = !shotPath.empty() || !filmDir.empty() || bench;

    Canvas canvas("Vulkan Deferred - Race quad in smoke",
                  {{"size", std::pair<int, int>{1600, 900}}, {"vsync", false}, {"headless", headless}});
    VulkanRenderer renderer(canvas);
    renderer.setDlss(upscaler == "dlss");
    renderer.setFsr(upscaler == "fsr");

    Scene       scene;
    std::shared_ptr<DirectionalLight> sun;
    if (!sky.empty()) {
        // An HDRI sky: it is the background, the ambient light and (the renderer's one-sun policy: no explicit
        // DirectionalLight in the scene) the sun, extracted from the map, with its shadows and volumetric light.
        std::shared_ptr<Texture> tex;
        if (sky == "sunset") {
            tex = makeSunset(sunElev, sunEnergy);
        } else {
            RGBELoader hdr;
            tex = hdr.load(std::string(DATA_FOLDER) + "/textures/env/" + sky + ".hdr");
        }
        if (!tex) {
            std::cerr << "cannot load the sky " << sky << "\n";
            return 1;
        }
        tex->mapping     = Mapping::EquirectangularReflection;
        scene.background = tex;
        scene.environment = tex;
        renderer.toneMapping         = ToneMapping::ACESFilmic;
        renderer.toneMappingExposure = exposure;
        renderer.setAutoExposure(false);
        renderer.setDeferredStarfield(0.f);
        VulkanRenderer::HeightFogSettings hf;
        hf.baseY       = 0.f;
        hf.density     = 0.0015f;
        hf.falloff     = 2.f;
        hf.noiseAmount = 0.2f;
        renderer.setHeightFog(hf);
    } else {
        const Color skyC(0.58f, 0.72f, 0.92f);
        renderer.setClearColor(skyC);
        scene.background = skyC;
        renderer.toneMapping         = ToneMapping::ACESFilmic;
        renderer.toneMappingExposure = exposure;
        renderer.setAutoExposure(false);
        renderer.setDeferredStarfield(0.f);
        VulkanRenderer::HeightFogSettings hf;
        hf.baseY       = 0.f;
        hf.density     = 0.003f;
        hf.falloff     = 3.f;
        hf.noiseAmount = 0.3f;
        renderer.setHeightFog(hf);
        sun = DirectionalLight::create();
        sun->color.setRGB(1.00f, 0.96f, 0.88f);
        sun->intensity = 2.6f;
        sun->position.set(4.f, 6.5f, 3.f);
        scene.add(sun);
        auto ambient = AmbientLight::create();
        ambient->color.setRGB(0.55f, 0.66f, 0.86f);
        ambient->intensity = 1.1f;
        scene.add(ambient);
    }

    auto ground = Mesh::create(PlaneGeometry::create(6000.f, 6000.f, 1, 1),
                               MeshStandardMaterial::create(MeshStandardMaterial::Params{}.color(Color(0.16f, 0.13f, 0.10f)).roughness(0.95f).metalness(0.f)));
    ground->rotateX(-math::PI / 2.f);
    scene.add(ground);

    // ── the smoke: a 3.2 m box on the ground, 2.5 cm cells at 128^3, so a 5 cm rotor is two cells across ────
    const Vector3 boxCenter(0.f, 1.6f, 0.f), boxHalf(1.6f, 1.6f, 1.6f);
    auto          smoke = ParticleField::createGridSmoke(boxCenter, boxHalf, static_cast<std::uint32_t>(res));
    auto&         gs    = smoke->gridSmoke();
    gs.solidFloor       = true;
    gs.buoyancy         = buoy;
    gs.dissipation      = 0.08f;
    gs.cooling          = 0.5f;
    gs.vorticity        = vort;
    gs.damping          = 0.01f;
    gs.sigma            = sigma;
    gs.maxSpeed         = 30.f;
    gs.pressureIterations = std::uint32_t(iters);
    gs.wind.set(0.f, 0.f, 0.f);
    {
        ParticleField::GridSmoke::Source s;
        s.position.set(0.f, 0.06f, 0.f);
        s.radius        = 0.13f;
        s.density       = rate;
        s.temperature   = 4.f;
        s.velocity.set(0.f, 1.4f, 0.f);
        s.velocityBlend = 5.f;
        s.noise         = 0.7f;
        gs.sources.push_back(s);
    }
    auto& dr      = smoke->densityRepr();
    dr.albedo     = Color(0.64f, 0.64f, 0.66f);
    dr.anisotropy = aniso;
    scene.add(smoke);

    // ── the quad ────────────────────────────────────────────────────────────
    std::shared_ptr<Group> drone;
    Object3D*              motorNode[4]{};
    if (!noDrone) {
        GLTFLoader loader;
        const auto path = std::filesystem::weakly_canonical(dronePath);
        auto       res3 = loader.load(path);
        if (!res3) {
            std::cerr << "cannot load " << path << " (python/examples/uav/build_racer_blender.py makes it; or --no-drone)\n";
            return 1;
        }
        drone = Group::create();
        res3->scene->scale.setScalar(kDrawn);
        drone->add(res3->scene);
        scene.add(drone);
        // The blades are hidden and each rotor is drawn as a faint disc: a real blade at this rate is sharp and
        // frozen in a still and a strobe in a film.
        auto discMat = MeshBasicMaterial::create(MeshBasicMaterial::Params{}.color(Color(0.86f, 0.87f, 0.88f)).transparent(true).opacity(0.22f).side(Side::Double).depthWrite(false));
        for (int i = 0; i < 4; ++i) {
            const std::string n = std::string("motor_") + kMotorName[i];
            motorNode[i]        = res3->scene->getObjectByName(n);
            if (auto* b = res3->scene->getObjectByName(std::string("prop_blades_") + kMotorName[i])) b->visible = false;
            if (motorNode[i]) {
                auto disc = Mesh::create(CircleGeometry::create(kPropR / kDrawn, 48), discMat);
                disc->rotateX(-math::PI / 2.f);
                disc->position.y = 0.035f;// above the bells, where the blades were
                motorNode[i]->add(disc);
            }
        }
        res3->scene->traverseType<Mesh>([](Mesh& m) { m.castShadow = true; });
    }

    // ONE place the clock is read: the drone's pose, the colliders and the sources, and the smoke's clock.
    constexpr double kDt = 1.0 / 60.0;
    const auto       tick = [&](double t) {
        gs.time = t;
        if (!drone) return;
        const Pose now  = flightAt(t);
        const Pose prev = flightAt(t - kDt);
        drone->position.copy(now.p);
        drone->quaternion.copy(now.q);

        gs.colliders.clear();
        gs.sources.resize(1);
        // The centre stack: a capsule from where it was a step ago to where it is.
        {
            ParticleField::GridSmoke::Collider c;
            c.a        = prev.p;
            c.b        = now.p;
            c.radius   = 0.045f;
            c.velocity = (now.p - prev.p) * float(1.0 / kDt);
            gs.colliders.push_back(c);
        }
        for (int i = 0; i < 4; ++i) {
            const Vector3 m0 = motorWorld(prev, i), m1 = motorWorld(now, i);
            ParticleField::GridSmoke::Collider c;
            c.a        = m0;
            c.b        = m1;
            c.radius   = 0.03f;
            c.velocity = (m1 - m0) * float(1.0 / kDt);
            gs.colliders.push_back(c);
            // The downwash: no smoke, air thrown down the thrust axis at the rotor's induced speed.
            ParticleField::GridSmoke::Source s;
            s.position      = m1 - now.up * 0.02f;
            s.radius        = kPropR * 0.95f;
            s.density       = 0.f;
            s.temperature   = 0.f;
            const float vw  = 9.f * std::sqrt(std::max(now.thrust, 0.2f));
            s.velocity      = now.up.clone().multiplyScalar(-vw) + now.v * 0.5f;
            s.velocityBlend = 30.f;
            s.noise         = 0.f;
            gs.sources.push_back(s);
        }
    };

    PerspectiveCamera camera(40.f, canvas.aspect(), 0.03f, 300.f);
    camera.position.set(2.3f, 1.45f, 2.9f);
    if (cap.camPos) camera.position.copy(*cap.camPos);
    const Vector3 target = cap.camTarget.value_or(Vector3(0.f, 1.2f, 0.f));
    camera.lookAt(target);
    // --backlit: with an HDRI the sun is wherever the map has it, so the camera goes to the far side of the plume from
    // it (rotated camAz degrees round the vertical) and looks into the light: forward scattering lights the smoke's edges.
    if (!sky.empty()) {
        canvas.animateOnce([&] { renderer.render(scene, camera); });// the env is processed on the first frame
        if (renderer.envSunFound()) {
            const Vector3 sd = renderer.envSunDirection();
            std::printf("[sky] %s: sun toward (%.3f, %.3f, %.3f), elevation %.1f deg, azimuth %.1f deg\n", sky.c_str(),
                        double(sd.x), double(sd.y), double(sd.z), double(std::asin(sd.y) * 180.f / math::PI),
                        double(std::atan2(sd.z, sd.x) * 180.f / math::PI));
            if (backlit && !cap.camPos) {
                const float a  = camAz * math::PI / 180.f;
                Vector3     sh(sd.x, 0.f, sd.z);
                sh.normalize();
                const Vector3 r(sh.x * std::cos(a) - sh.z * std::sin(a), 0.f, sh.x * std::sin(a) + sh.z * std::cos(a));
                camera.position.set(target.x - r.x * camDist, camH, target.z - r.z * camDist);
                camera.lookAt(target);
            }
        } else {
            std::printf("[sky] %s: no sun found in the map\n", sky.c_str());
        }
    }
    canvas.onWindowResize([&](WindowSize s) {
        camera.aspect = s.aspect();
        camera.updateProjectionMatrix();
        renderer.setSize(s);
    });
    // --track: the eye holds still, the aim follows the quad, a little late so it does not jitter.
    Vector3    aim = target;
    const auto look = [&](double t) {
        if (track && drone) {
            const Vector3 p = flightAt(t).p;
            aim += (p - aim) * 0.25f;
            camera.lookAt(aim);
        }
    };

    if (bench) {
        for (int i = 0; i < 400; ++i) {
            tick(double(i) * kDt);
            canvas.animateOnce([&] { renderer.render(scene, camera); });
        }
        double ms = 0, gpu = 0;
        for (int i = 400; i < 560; ++i) {
            tick(double(i) * kDt);
            canvas.animateOnce([&] { renderer.render(scene, camera); });
            const auto tm = renderer.lastFrameTimings();
            ms += tm.particleDensityMs;
            gpu += tm.gpuTotalMs;
        }
        std::printf("[bench] %d^3: density block %.3f ms, whole frame %.3f ms\n", res, ms / 160.0, gpu / 160.0);
        return 0;
    }

    if (!filmDir.empty()) {
        namespace fs = std::filesystem;
        fs::create_directories(filmDir);
        const double step = 1.0 / double(fps);
        const int    n    = int(seconds * float(fps));
        gs.maxStepsPerFrame = std::max<std::uint32_t>(8u, std::uint32_t(std::ceil(step / kDt)) + 1u);
        for (int i = 0; i < n; ++i) {
            const double t = double(i) * step;
            tick(t);
            look(t);
            canvas.animateOnce([&] { renderer.render(scene, camera); });
            char name[64];
            std::snprintf(name, sizeof(name), "f%05d.png", i);
            renderer.writeFramebuffer((fs::path(filmDir) / name).string());
        }
        std::printf("[film] %d frames -> %s\n", n, filmDir.c_str());
        return 0;
    }

    if (!shotPath.empty()) {
        // The solve runs at 60 steps a second to shotT, then the clock holds so the smoke stops moving and TAA converges.
        const int warm   = int(shotT / kDt);
        const int settle = cap.frames.value_or(48);
        for (int i = 0; i < warm + settle; ++i) {
            const double t = std::min(double(i), double(warm)) * kDt;
            tick(t);
            look(t);
            canvas.animateOnce([&] { renderer.render(scene, camera); });
        }
        renderer.writeFramebuffer(shotPath);
        std::printf("[shot] %s (t=%.2f s)\n", shotPath.c_str(), double(shotT));
        return 0;
    }

    OrbitControls controls(camera, canvas);
    controls.target.copy(target);
    controls.update();
    Clock  clock;
    double simT = 0.0;
    canvas.animate([&] {
        simT += clock.getDelta();
        tick(simT);
        renderer.render(scene, camera);
    });
    return 0;
}
